import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on('pageerror', error => console.log('PAGE ERROR:', error.message));
page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE:', message.text()); });
page.on('response', response => { if (response.status() >= 400) console.log('HTTP:', response.status(), response.url()); });
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
console.log('Paint:', await page.locator('.hero-scene img').evaluate(image => ({ complete:image.complete,naturalWidth:image.naturalWidth, opacity:getComputedStyle(image).opacity, visibility:getComputedStyle(image).visibility, clip:getComputedStyle(image.parentElement).clipPath, bounds:JSON.stringify(image.getBoundingClientRect()) })));
await page.screenshot({ path: 'artifacts/production-first.png' });
await page.evaluate(() => document.querySelectorAll('img').forEach(image => image.loading = 'eager'));
await page.waitForFunction(() => Array.from(document.images).every(image => image.complete && image.naturalWidth > 0));
await page.screenshot({ path: 'artifacts/production-full.png', fullPage: true });
await page.locator('.directory-toggle').click();
await page.waitForTimeout(2000);
console.log('Directory:', await page.locator('.directory-toggle').getAttribute('aria-expanded'));
console.log('Rows:', await page.locator('.work-card').count());
await page.locator('#about').scrollIntoViewIfNeeded();
await page.waitForTimeout(2000);
console.log('Images:', await page.locator('img').evaluateAll(images => images.map(image => ({ src: image.getAttribute('src'), width: image.naturalWidth, loading: image.loading, rect: image.getBoundingClientRect().top }))));
await page.screenshot({ path: 'artifacts/diagnose-about.png' });
await browser.close();
